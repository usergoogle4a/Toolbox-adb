fun resolveStrings(language: AppLanguage): AppStrings {
    return when (language) {
        AppLanguage.ENGLISH -> EnStrings
        AppLanguage.RUSSIAN -> RuStrings
        AppLanguage.SYSTEM -> {
            val lang = Locale.getDefault().language
            if (lang == "ru" || lang == "be" || lang == "uk") RuStrings else EnStrings
        }
    }
}

